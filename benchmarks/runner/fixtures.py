"""Disposable deterministic fixtures for implementation-episode plumbing.

These fixtures test the runner, not the product claims of GravitasBench.  Each
task gets an isolated worktree and a task-specific acceptance test; real,
licensed repositories can replace this factory without changing the runner.

Leakage design: the solver worktree receives the broken implementation plus a
trivial import smoke test ONLY.  The acceptance test is generated by the same
deterministic function but materialized into a runner-private directory the
solver can never read; it executes post-hoc against the final worktree.  The
episode records only its sha256 (`hidden_validator_hash`), never its content.
"""
import hashlib
import shutil
from pathlib import Path


CASES = (
    ("normalize", "def transform(value):\n    return value\n", "self.assertEqual(transform('  Mixed Case  '), 'mixed case')"),
    ("deduplicate", "def transform(value):\n    return value\n", "self.assertEqual(transform(['b', 'a', 'b']), ['a', 'b'])"),
    ("redact", "def transform(value):\n    return value\n", "self.assertEqual(transform({'token': 'secret', 'name': 'Ada'}), {'token': '[redacted]', 'name': 'Ada'})"),
    ("clamp", "def transform(value):\n    return value\n", "self.assertEqual(transform(-3), 0)"),
    ("slug", "def transform(value):\n    return value\n", "self.assertEqual(transform('Hello, World!'), 'hello-world')"),
)

SMOKE_TEST = (
    "import sys\nimport unittest\nfrom pathlib import Path\n\n"
    "sys.path.insert(0, str(Path(__file__).parents[1] / 'src'))\n"
    "import target\n\n"
    "class SmokeTests(unittest.TestCase):\n"
    "    def test_imports(self):\n"
    "        self.assertTrue(callable(target.transform))\n"
)


def case_for(task_id):
    return CASES[sum(ord(char) for char in task_id) % len(CASES)]


def hidden_test_source(task_id):
    """Acceptance test source. Runner-private: never written into the worktree."""
    _, _, assertion = case_for(task_id)
    return (
        "import sys\nimport unittest\nfrom pathlib import Path\n\n"
        "sys.path.insert(0, str(Path(__file__).parents[1] / 'src'))\n"
        "from target import transform\n\n"
        "class HiddenAcceptanceTests(unittest.TestCase):\n"
        "    def test_expected_behavior(self):\n"
        f"        {assertion}\n"
    )


def hidden_test_hash(task_id):
    return hashlib.sha256(hidden_test_source(task_id).encode()).hexdigest()


def materialize(task_id, destination):
    """Create a clean, intentionally failing SOLVER worktree and return metadata.

    The worktree contains the broken implementation and an import smoke test
    only.  Acceptance assertions live exclusively in ``hidden_test_source``.
    """
    destination = Path(destination)
    if destination.exists():
        shutil.rmtree(destination)
    (destination / "src").mkdir(parents=True)
    (destination / "tests").mkdir()
    name, implementation, _ = case_for(task_id)
    (destination / "src" / "target.py").write_text(implementation)
    (destination / "tests" / "test_smoke.py").write_text(SMOKE_TEST)
    return {"fixture_kind": name, "allowed_write_scope": ["src/target.py"],
            "hidden_validator_hash": hidden_test_hash(task_id),
            "validator": "hidden acceptance test (sha256 recorded, content withheld)"}


def check_holdout(task_id, manifest, include_holdout=False):
    """Refuse holdout tasks unless explicitly included. Returns an error or None."""
    holdout = set((manifest.get("holdout") or {}).get("tasks", []))
    if task_id in holdout and not include_holdout:
        return (f"task {task_id} is in the holdout set "
                f"({sorted(holdout)}); rerun with --include-holdout to use it")
    return None
